// Keep the established cascade order while serving one render-blocking file.
// Run after editing any of these sources; no package install is required.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../maanshan');
const files = [
  'styles.css', 'visuals.css', 'exploration.css', 'exploration-loading.css',
  'shishi.css', 'refresh.css', 'challenge.css', 'lesson-map.css', 'platform.css',
  'poetry-card.css', 'simplify.css', 'large-type.css', 'compact-activities.css',
  'extension.css', 'animation.css', 'mobile-tablet.css', 'exploration-touch.css'
];
const css = '/* Generated by scripts/build-maanshan-css.cjs. Edit the source stylesheets. */\n'
  + files.map(file => `/* ${file} */\n${fs.readFileSync(path.join(root, file), 'utf8').trim()}\n`).join('\n');
fs.writeFileSync(path.join(root, 'app.bundle.css'), css);
console.log(`Bundled ${files.length} stylesheets (${Buffer.byteLength(css)} bytes).`);
