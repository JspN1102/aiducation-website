// Reuse the checked-in official Lucide runtime and icon nodes, without npm.
// Run after adding an icon name to the Maanshan HTML or JavaScript sources.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../maanshan');
const vendor = path.join(root, 'vendor');
const source = fs.readFileSync(path.join(vendor, 'lucide.min.js'), 'utf8');
const license = fs.readFileSync(path.join(vendor, 'licenses/lucide.txt'), 'utf8');
const context = {};
vm.runInNewContext(source, context, {timeout: 1000});
const official = context.lucide;
assert(official?.icons && typeof official.createIcons === 'function', 'Unsupported Lucide vendor bundle');
const pascal = name => name.split(/[-_\s]+/).filter(Boolean).map(part => part[0].toUpperCase() + part.slice(1)).join('');
const names = new Set();
const scanned = [];
for (const file of fs.readdirSync(root).filter(name => /\.(?:html|m?js)$/.test(name)).sort()) {
  const text = fs.readFileSync(path.join(root, file), 'utf8');
  // Modules with their own inline SVG helpers are deliberately excluded.
  if (!/data-lucide|lucide\??\s*\.\s*createIcons/.test(text)) continue;
  scanned.push(file);
  // Include string-valued NAV/menu entries and ternaries as well as icon('x').
  // A conservative superset prevents dynamic icon names being tree-shaken out.
  for (const match of text.matchAll(/['"]([a-z][a-z0-9]*(?:-[a-z0-9]+)*)['"]/g)) {
    const name = pascal(match[1]);
    if (Object.hasOwn(official.icons, name)) names.add(name);
  }
  for (const match of text.matchAll(/(?:\bicon\(\s*['"]|\bdata-lucide=['"])([a-z][a-z0-9-]*)['"]/g)) {
    assert(Object.hasOwn(official.icons, pascal(match[1])), `Unknown Lucide icon ${match[1]} in ${file}`);
  }
}
const selected = Object.fromEntries([...names].sort().map(name => [name, official.icons[name]]));
// Keep the upstream DOM renderer verbatim, including aria and class merging.
// Stop at the first icon-node array, before the full icon catalog starts.
const runtimeStart = source.indexOf('"use strict";') + '"use strict";'.length;
const firstNode = source.slice(runtimeStart).match(/,[\w$]+=\[\["(?:path|circle|rect|line|polyline|polygon|ellipse)"/);
assert(runtimeStart > 12 && firstNode, 'Vendor runtime boundary changed; inspect the new official bundle');
const runtime = source.slice(runtimeStart, runtimeStart + firstNode.index) + ';';
const factory = official.createIcons.toString();
const defaultMap = factory.match(/^\(\{icons:\w+=([\w$]+)/)?.[1];
assert(defaultMap && /^[$\w]+$/.test(official.createIcons.name) && /^[$\w]+$/.test(official.createElement.name), 'Vendor export structure changed');
const output = `/* Generated by scripts/build-maanshan-icons.cjs from official Lucide v1.42.0.\n`
  + ` * Sources: ${scanned.join(', ')}. ${names.size} local icon names.\n\n${license.replaceAll('*/', '* /')}\n*/\n`
  + `(()=>{"use strict";${runtime}const ${defaultMap}=${JSON.stringify(selected)};`
  + `const ${official.createIcons.name}=${factory};`
  + `globalThis.lucide={...${defaultMap},icons:${defaultMap},createElement:${official.createElement.name},createIcons:${official.createIcons.name}};})();\n`;
assert(Buffer.byteLength(output) < 30000, 'Subset exceeds its 30 KB budget');
const check = {};
vm.runInNewContext(output, check, {timeout: 1000});
assert.equal(Object.keys(check.lucide.icons).length, names.size);
fs.writeFileSync(path.join(vendor, 'lucide-maanshan.js'), output);
console.log(JSON.stringify({icons:names.size,sources:scanned,bytes:Buffer.byteLength(output),originalBytes:Buffer.byteLength(source),names:[...names].sort()}));
