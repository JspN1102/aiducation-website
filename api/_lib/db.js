import mysql from 'mysql2/promise';
import pg from 'pg';

/**
 * DB_DRIVER is explicitly "postgres" (or "postgresql") or "mysql" (default).
 * DB_HOST, DB_PORT, DB_USER, DB_PASS, DB_NAME configure either driver.
 * With no DB_HOST, callers retain the existing local-only fallback.
 * SQL dialects are supplied explicitly; placeholders are never rewritten.
 */
let pool = null;

function getDriver() {
  const driver = (process.env.DB_DRIVER || 'mysql').toLowerCase();
  if (driver === 'postgres' || driver === 'postgresql') return 'postgres';
  if (driver === 'mysql') return driver;
  throw new Error('Unsupported DB_DRIVER');
}

function getPool() {
  if (pool) return pool;
  if (!process.env.DB_HOST) return null;
  const driver = getDriver();
  const shared = {
    host: process.env.DB_HOST,
    port: Number(process.env.DB_PORT) || (driver === 'postgres' ? 5432 : 3306),
    user: process.env.DB_USER || (driver === 'postgres' ? 'postgres' : 'root'),
    password: process.env.DB_PASS || process.env.DB_PASSWORD || '',
    database: process.env.DB_NAME || 'maanshan'
  };
  if (driver === 'postgres') {
    pool = new pg.Pool({
      ...shared,
      max: 5,
      connectionTimeoutMillis: 5000,
      idleTimeoutMillis: 30000,
      statement_timeout: 10000,
      application_name: 'maanshan',
      keepAlive: true
    });
    // Idle sockets can fail independently of a request. Do not crash the service.
    pool.on('error', err => logDbError('idle connection', err));
  } else {
    pool = mysql.createPool({
      ...shared,
      waitForConnections: true,
      connectionLimit: 5,
      queueLimit: 0,
      connectTimeout: 5000,
      enableKeepAlive: true,
      keepAliveInitialDelay: 10000
    });
  }
  return pool;
}

function logDbError(operation, err) {
  // Driver messages can contain SQL and student payloads; log only a safe code.
  const code = typeof err?.code === 'string' && /^[A-Z0-9_]+$/i.test(err.code)
    ? err.code : 'DATABASE_ERROR';
  console.error(`DB ${operation} failed: ${code}`);
}

function selectSql(sql) {
  const statement = typeof sql === 'string' ? sql : sql?.[getDriver()];
  if (typeof statement !== 'string' || !statement.trim()) {
    throw new Error('Missing SQL for database driver');
  }
  return statement;
}

/** Return rows, or null when unavailable. */
export async function query(sql, params = []) {
  try {
    const p = getPool();
    if (!p) return null;
    const statement = selectSql(sql);
    if (getDriver() === 'postgres') return (await p.query(statement, params)).rows;
    const [rows] = await p.execute(statement, params);
    return rows;
  } catch (err) {
    logDbError('query', err);
    return null;
  }
}

/** Return the driver result, or false when unavailable. */
export async function execute(sql, params = []) {
  try {
    const p = getPool();
    if (!p) return false;
    const statement = selectSql(sql);
    if (getDriver() === 'postgres') return await p.query(statement, params);
    const [result] = await p.execute(statement, params);
    return result;
  } catch (err) {
    logDbError('execute', err);
    return false;
  }
}

/** Configuration check only; request failures still use the local-only fallback. */
export function isDbReady() {
  try {
    return !!getPool();
  } catch (err) {
    logDbError('configuration', err);
    return false;
  }
}

/**
 * 建表 SQL（首次部署运行一次即可）
 */
export const INIT_SQL = `
CREATE TABLE IF NOT EXISTS student_data (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  student_id  VARCHAR(32)  NOT NULL,
  name        VARCHAR(64)  DEFAULT '',
  grade       TINYINT      NOT NULL,
  cls         CHAR(1)      NOT NULL,
  poem_id     TINYINT      NOT NULL,
  section     ENUM('reading','writing','report') NOT NULL,
  payload     JSON         NOT NULL,
  sync_id     VARCHAR(64)  DEFAULT NULL,
  created_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP    DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY  uk_sync (sync_id),
  KEY         idx_class_poem (grade, cls, poem_id),
  KEY         idx_student_poem (student_id, poem_id, section)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
`;

export const POSTGRES_INIT_SQL = [
  `CREATE TABLE IF NOT EXISTS student_data (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  VARCHAR(32) NOT NULL,
    name        VARCHAR(64) DEFAULT '',
    grade       SMALLINT NOT NULL,
    cls         CHAR(1) NOT NULL,
    poem_id     SMALLINT NOT NULL,
    section     VARCHAR(16) NOT NULL CHECK (section IN ('reading', 'writing', 'report')),
    payload     JSONB NOT NULL,
    sync_id     VARCHAR(64) UNIQUE,
    created_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
  )`,
  'CREATE INDEX IF NOT EXISTS idx_class_poem ON student_data (grade, cls, poem_id)',
  'CREATE INDEX IF NOT EXISTS idx_student_poem ON student_data (student_id, poem_id, section)'
];

/** Run once at deployment; never erase or truncate existing student data. */
export async function initializeSchema() {
  try {
    if (!isDbReady()) return false;
    const statements = getDriver() === 'postgres' ? POSTGRES_INIT_SQL : [INIT_SQL];
    for (const statement of statements) {
      if (await execute(statement) === false) return false;
    }
    return true;
  } catch (err) {
    logDbError('initialization', err);
    return false;
  }
}

/** Used by deployment checks and graceful service shutdown. */
export async function closePool() {
  const previous = pool;
  pool = null;
  if (previous) await previous.end();
}
